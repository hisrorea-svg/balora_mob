}

/// Queue Service Provider.
@Riverpod(keepAlive: true)
QueueService queueService(Ref ref) {
  final dao = ref.watch(queueDaoProvider);
  return QueueService(dao);
}

/// Sync Engine Provider.
///
/// Note: stays a regular (non-generated) `Provider` here because no
/// generated provider depends on it directly and it is consumed only from
/// regular `ConsumerWidget`/`ConsumerStatefulWidget` screens. If it ever
/// becomes a dependency of a generated provider, promote it to `@Riverpod`.
final syncEngineProvider = Provider<SyncEngine>((ref) {
  final engine = SyncEngine(
    queueDao: ref.watch(queueDaoProvider),
    apiClient: ref.watch(apiClientProvider),
    connectivity: ref.watch(connectivityMonitorProvider),
    webSocket: ref.watch(webSocketServiceProvider),
  );

  ref.onDispose(() {
    engine.dispose();
  });

  return engine;
});
