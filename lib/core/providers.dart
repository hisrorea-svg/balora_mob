/// Synchronous, mutable flag for "is this device currently linked to a
/// desktop". Drives the GoRouter redirect guard.
///
/// Set by:
/// - `SplashScreen` after the WS handshake resolves (true on success, false
///   on failure/no session).
/// - `PairingScreen` after a successful `pairWithQr` (true).
/// - `SettingsController.unpair` when the user explicitly unpairs (false).
@Riverpod(keepAlive: true)
class AuthState extends _$AuthState {
  @override
  bool build() => false;

  /// Flips the link-paired state for the GoRouter redirect guard.
  ///
  /// Exposed as a method because [Notifier.state] is protected — direct
  /// assignment via `ref.read(authStateProvider.notifier).state = …` is
  /// rejected by the analyzer.
  void set(bool value) => state = value;
}

/// API Client Provider.
@Riverpod(keepAlive: true)
ApiClient apiClient(Ref ref) {
  final dio = Dio(
    BaseOptions(
      connectTimeout: const Duration(seconds: 10),
      receiveTimeout: const Duration(seconds: 10),
      sendTimeout: const Duration(seconds: 10),
      headers: {
        'Content-Type': 'application/json',
        'Accept': 'application/json',
      },
    ),
  );

  dio.httpClientAdapter = IOHttpClientAdapter(
    createHttpClient: () {
      final client = HttpClient();
      // Accept local LAN TLS certificates generated by Balora Desktop
      // (tools/setup-mobile-tls.ps1).
      client.badCertificateCallback =
          (X509Certificate cert, String host, int port) => true;
      return client;
    },
  );

  dio.interceptors.addAll([LoggingInterceptor(), RetryInterceptor(dio)]);

  return ApiClient(dio);
}

/// Connectivity Provider — `.start()` is invoked eagerly so the underlying
/// network status stream is live from the first frame (audit: previously
/// `.start()` was never called and `_isConnected` stayed `true` forever).
@Riverpod(keepAlive: true)
ConnectivityMonitor connectivityMonitor(Ref ref) {
  final monitor = ConnectivityMonitor();
  monitor.start();
  ref.onDispose(monitor.dispose);
  return monitor;
}

/// The *single* source of the [WebSocketService] instance. Use this provider
/// everywhere — defining it in two different files was previously causing the
/// connection-state stream to subscribe to a *different* instance and miss
/// every connection event.
@Riverpod(keepAlive: true)
WebSocketService webSocketService(Ref ref) {
  final service = WebSocketService();
  ref.onDispose(service.dispose);
  return service;
}

@Riverpod(keepAlive: true)
class ConnectionState extends _$ConnectionState {
  @override
  bool build() {
    final webSocket = ref.watch(webSocketServiceProvider);
    final sub = webSocket.onConnectionChanged.listen((connected) {
      state = connected;
    });
    ref.onDispose(sub.cancel);
    return webSocket.isConnected;
  }
}

/// Queue DAO Provider.
@Riverpod(keepAlive: true)
QueueDao queueDao(Ref ref) {
  final db = ref.watch(appDatabaseProvider);
